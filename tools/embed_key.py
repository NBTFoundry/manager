"""Writes the include that bundles the apps public key with the manager
(src/package/apps_key.cpp): the one RSA public key every application package
is signed with. Only a public key is accepted. The include is rewritten only
when its content changes, so builds stay incremental. An empty path bundles
no key: the worker then accepts no application package."""
import os
from pathlib import Path
import sys


def literal(pem):
    lines = pem.decode("ascii").splitlines()
    if (len(lines) < 3 or lines[0] != "-----BEGIN PUBLIC KEY-----" or lines[-1] != "-----END PUBLIC KEY-----"
            or any(not line or any(c not in "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/="
                                   for c in line) for line in lines[1:-1])):
        raise ValueError("not a PEM public key")
    return "\n".join(f'    "{line}\\n"' for line in lines)


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: embed_key.py <public-key.pem or ''> <output.inc>")
    source, output = sys.argv[1], Path(sys.argv[2])
    body = literal(Path(source).read_bytes()) if source else '    ""'
    text = ("/* Generated by tools/embed_key.py: the apps public key bundled with the manager. */\n"
            f"static const char kAppsKeyPem[] =\n{body};\n")
    if not output.exists() or output.read_text() != text:
        temporary = output.with_suffix(".tmp")
        temporary.write_text(text)
        os.replace(temporary, output)


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, UnicodeDecodeError) as error:
        raise SystemExit(f"embed_key.py: {error}")
