"""The manager GUI's text catalogs (src/gui/text/<code>.txt) and the C++ they
become: include/nbt/gui/text_id.hpp and src/gui/text_tables.cpp.

    python3 tools/gui_text.py           # write the generated files
    python3 tools/gui_text.py --check   # fail when they are not up to date

A catalog has one `key = text` line per text; `#` starts a comment line.
en.txt defines the keys and their order; every other catalog has exactly the
same keys. Texts take `{1}` and `{2}`, replaced by strings at run time
(src/gui/text.cpp); a translation has the same placeholders as English, in
any order. The generated C++ is ASCII: other characters are octal escapes.
After changing a Chinese or Japanese text, regenerate the fonts too
(tools/make_fonts.py): they hold only the characters the catalogs use.
"""

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
CATALOGS = ROOT / "src" / "gui" / "text"
HEADER = ROOT / "include" / "nbt" / "gui" / "text_id.hpp"
TABLES = ROOT / "src" / "gui" / "text_tables.cpp"
# The order of nbt::model::Language (include/nbt/model/language.hpp).
LANGUAGES = ("en", "fr", "de", "it", "es", "zh", "ja")
KEY = re.compile(r"^[a-z][a-z0-9_]*$")
PLACEHOLDER = re.compile(r"\{[^}]*\}")
# Bytes in one text before its placeholders are filled (src/gui/ui_view.hpp kTextMax).
TEXT_MAX = 120


class CatalogError(Exception):
    pass


def parse(path):
    """The catalog's (key, text) pairs, in order."""
    entries, seen = [], set()
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        where = f"{path.relative_to(ROOT)}:{number}"
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        key, sep, text = raw.partition(" = ")
        if not sep or not KEY.match(key):
            raise CatalogError(f"{where}: expected 'key = text'")
        text = text.rstrip()
        if key in seen:
            raise CatalogError(f"{where}: {key} appears twice")
        if not text or any(ord(c) < 0x20 or 0x7f <= ord(c) < 0xa0 for c in text):
            raise CatalogError(f"{where}: {key} is empty or has a control character")
        for placeholder in PLACEHOLDER.findall(text):
            if placeholder not in ("{1}", "{2}"):
                raise CatalogError(f"{where}: {key} has {placeholder}; only {{1}} and {{2}}")
        if len(text.encode("utf-8")) > TEXT_MAX:
            raise CatalogError(f"{where}: {key} is longer than {TEXT_MAX} bytes")
        seen.add(key)
        entries.append((key, text))
    return entries


def load():
    """{code: {key: text}} and the keys in English order; checks every catalog."""
    english = parse(CATALOGS / "en.txt")
    keys = [key for key, _ in english]
    catalogs = {"en": dict(english)}
    for code in LANGUAGES[1:]:
        path = CATALOGS / f"{code}.txt"
        entries = dict(parse(path))
        missing = [key for key in keys if key not in entries]
        extra = [key for key in entries if key not in catalogs["en"]]
        if missing or extra:
            raise CatalogError(f"{path.relative_to(ROOT)}: missing {missing}, unknown {extra}")
        for key in keys:
            want = sorted(PLACEHOLDER.findall(catalogs["en"][key]))
            if sorted(PLACEHOLDER.findall(entries[key])) != want:
                raise CatalogError(f"{path.relative_to(ROOT)}: {key} needs the placeholders {want}")
        catalogs[code] = entries
    return catalogs, keys


def c_string(text):
    out = []
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7f:
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def header(keys):
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        "/* Generated by tools/gui_text.py from src/gui/text/en.txt: do not edit. */",
        "#ifndef NBT_GUI_TEXT_ID_HPP",
        "#define NBT_GUI_TEXT_ID_HPP",
        "",
        "namespace nbt {",
        "namespace gui {",
        "",
        "enum TextId {",
    ]
    lines += [f"    T_{key.upper()}," for key in keys]
    lines += ["    kTextCount", "};", "", "} // namespace gui", "} // namespace nbt", "", "#endif", ""]
    return "\n".join(lines)


def tables(catalogs, keys):
    lines = [
        "// SPDX-License-Identifier: MPL-2.0",
        "/* Generated by tools/gui_text.py from src/gui/text/<code>.txt: do not edit.",
        " * One row per text, in the languages' order (nbt/model/language.hpp). */",
        '#include "nbt/gui/text.hpp"',
        "",
        "namespace nbt {",
        "namespace gui {",
        "namespace {",
        "",
        f"const char *const kTexts[kTextCount][{len(LANGUAGES)}] = {{",
    ]
    for key in keys:
        row = ", ".join(c_string(catalogs[code][key]) for code in LANGUAGES)
        lines.append(f"    {{{row}}}, // {key}")
    lines += [
        "};",
        "",
        "} // namespace",
        "",
        "const char *textIn(model::Language language, TextId id) {",
        "    const unsigned i = static_cast<unsigned>(id), l = static_cast<unsigned>(language);",
        f"    return i < kTextCount && l < {len(LANGUAGES)} ? kTexts[i][l] : \"\";",
        "}",
        "",
        "} // namespace gui",
        "} // namespace nbt",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when the generated files are stale")
    args = parser.parse_args()
    try:
        catalogs, keys = load()
    except CatalogError as error:
        print(f"gui_text: {error}", file=sys.stderr)
        return 1
    outputs = {HEADER: header(keys), TABLES: tables(catalogs, keys)}
    stale = [path for path, text in outputs.items()
             if not path.is_file() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"gui_text: {path.relative_to(ROOT)} is stale: run tools/gui_text.py", file=sys.stderr)
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
        print(f"gui_text: wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
